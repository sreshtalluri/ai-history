export type CitationId = keyof typeof citations;

export const citationIds = Object.keys(citations) as CitationId[];

const doiUrl = (doi: string) => `https://doi.org/${doi}`;
const arxivUrl = (id: string) => `https://arxiv.org/abs/${id}`;

export interface CitationLink {
  label: string;
  url: string;
}

/** The links to show for a reference, best first. */
export function citationLinks(c: Citation): CitationLink[] {
  const links: CitationLink[] = [];
  if (c.doi) links.push({ label: `DOI ${c.doi}`, url: doiUrl(c.doi) });
  if (c.arxiv) links.push({ label: `arXiv:${c.arxiv}`, url: arxivUrl(c.arxiv) });
  if (c.arxiv) links.push({ label: 'PDF', url: `https://arxiv.org/pdf/${c.arxiv}` });
  if (c.url) links.push({ label: c.type === 'paper' || c.type === 'report' ? 'Read online' : 'Source', url: c.url });
  return links;
}

/** Plain-text APA-style reference, for copying. */
export function formatCitation(c: Citation): string {
  let s = `${c.authors} (${c.year}). ${c.title}.`;
  if (c.venue) {
    s += ` ${c.venue}`;
    if (c.volume) s += `, ${c.volume}`;
    if (c.issue) s += `(${c.issue})`;
    if (c.pages) s += `, ${c.pages}`;
    s += '.';
  }
  if (c.doi) s += ` ${doiUrl(c.doi)}`;
  else if (c.arxiv) s += ` arXiv:${c.arxiv}. ${arxivUrl(c.arxiv)}`;
  else if (c.url) s += ` ${c.url}`;
  return s;
}
