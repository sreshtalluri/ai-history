/** For each event, the shifts it belongs to and its role in each. */
export const shiftsByEvent = new Map<string, { shift: Shift; role: ShiftRole; note: string }[]>();
for (const shift of shifts) {
  for (const m of shift.moments) {
    const list = shiftsByEvent.get(m.event) ?? [];
    list.push({ shift, role: m.role, note: m.note });
    shiftsByEvent.set(m.event, list);
  }
}
